// Sound events: the moment a representative pendulum's bob crosses the vertical centre line
// through the pivot (endpoint x changes sign). Times are linearly interpolated inside one RK4 step
// (1/600 s). Physics comes unchanged from sim.js. Writes sound_events.js.
global.window = global;
require("./revision_run.js");
const M = require("./sim.js"), run = window.REVISION_RUN, fs = require("fs");
const REPS = 16, SECONDS = 60;
const reps = Array.from({ length: REPS }, (_, k) => Math.round(k * (run.count - 1) / (REPS - 1)));
const out = { reps, event: "bob crosses the vertical line through the pivot", seconds: SECONDS, dt: M.DT, cases: [] };
const bx = (sim, i) => Math.sin(sim.theta1[i]) + Math.sin(sim.theta2[i]);
for (const c of run.cases) {
  const sim = M.makeSim({ n: run.count, initial: c.initial }), ev = [];
  let prev = reps.map(i => bx(sim, i));
  const steps = Math.round(SECONDS / M.DT);
  for (let s = 0; s < steps; s++) {
    sim.step();
    reps.forEach((i, k) => {
      const x = bx(sim, i), p = prev[k];
      if ((p < 0) !== (x < 0) && p !== x) {
        const t = (s + p / (p - x)) * M.DT;
        const y = -Math.cos(sim.theta1[i]) - Math.cos(sim.theta2[i]);   // bob height (m), below pivot < 0
        ev.push([+t.toFixed(6), k, +y.toFixed(3), x > p ? 1 : -1]);
      }
      prev[k] = x;
    });
  }
  ev.sort((a, b) => a[0] - b[0]);
  out.cases.push({ id: c.id, events: ev });
  console.log(c.id, "events:", ev.length, "rate/s:", (ev.length / SECONDS).toFixed(1));
}
fs.writeFileSync(__dirname + "/sound_events.js", "// Generated by measure_sound.js: [t (s), representative k, bob y (m), direction]\nwindow.SOUND_EVENTS=" + JSON.stringify(out) + ";\n");
