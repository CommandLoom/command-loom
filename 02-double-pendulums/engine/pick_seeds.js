// Measure first, edit later. No target-second triggers and no trajectory correction.
"use strict";
const fs = require("fs"), path = require("path"), M = require("./sim.js");
const sampleDt = 1 / 30, horizon = 45, probeN = 41, span = (M.N - 1) * M.EPS;
function measure(o, end, monitor = false) {
  const s = M.makeSim({ ...o, monitorEnergy: monitor });
  let a = null, b = null, peak = 0;
  const checkpoints = [];
  const curve = [];
  for (let frame = 1; frame <= Math.ceil(end / sampleDt); frame++) {
    s.advanceTo(frame * sampleDt); const d = s.spread(); peak = Math.max(peak, d);
    if (a === null && d >= .01) a = s.t;
    if (b === null && d >= .25) b = s.t;
    if (!monitor && a !== null && b !== null) break;
    if (monitor && frame % 300 === 0) { checkpoints.push(s.snapshot()); console.log('checked seconds', s.t, 'energy drift', s.maxEnergyDrift); }
    if (frame % 15 === 0) curve.push([+s.t.toFixed(6), d]);
  }
  return { smallAt: a, largeAt: b, peak, curve, checkpoints, maxEnergyDrift: s.maxEnergyDrift, end: s.t };
}
const candidates = [];
for (let seed = 1; seed <= 8; seed++) {
  const r = measure({ n: probeN, seed, span }, horizon);
  console.log("probe", seed, JSON.stringify({ small: r.smallAt, large: r.largeAt, peak: r.peak }));
  if (r.smallAt && r.largeAt && r.smallAt > 6 && r.largeAt < 40) candidates.push({ seed, ...r });
}
if (!candidates.length) throw new Error("No measured candidate; extend the observation horizon.");
candidates.sort((a, b) => (b.largeAt - b.smallAt) - (a.largeAt - a.smallAt));
let seed, main, fine, finest;
const rejected = [];
for (const candidate of candidates) {
  seed = candidate.seed;
  main = measure({ n: M.N, seed }, 45);
  fine = measure({ n: M.N, seed, dt: M.DT / 2 }, 45);
  finest = measure({ n: M.N, seed, dt: M.DT / 4 }, 45);
  const valid = ["smallAt", "largeAt"].every(k => main[k] && fine[k] && finest[k] &&
    Math.abs(fine[k] - finest[k]) / finest[k] <= .05 && Math.abs(main[k] - finest[k]) / finest[k] <= .05);
  console.log("full population refinement", JSON.stringify({ seed,
    coarse: [main.smallAt,main.largeAt], half: [fine.smallAt,fine.largeAt], quarter: [finest.smallAt,finest.largeAt], valid }));
  if(valid) break;
  rejected.push(seed);
}
if(!seed || rejected.includes(seed)) throw new Error("No converged candidate; reduce timestep. Do not loosen the tolerance.");
const P = 2 * Math.PI * Math.sqrt(1 / M.G);
const endTime = Math.ceil((main.largeAt + 100 * P) * 30) / 30;
const checked = measure({ n: M.N, seed }, endTime, true);
if (!(checked.maxEnergyDrift < 1e-4)) throw new Error("Energy budget failed; reduce dt.");
const out = { version: 1, model: "Ideal planar point-mass double pendulum",
  source: "Shinbrot et al., American Journal of Physics 60(6), 491–499 (1992), Appendix B",
  units: { length: "m", mass: "kg", time: "s", angle: "rad" },
  assumed: { l1: 1, l2: 1, m1: 1, m2: 1 }, g: M.G, dt: M.DT, count: M.N, epsilon: M.EPS,
  seed, initial: M.initial(seed), sampleInterval: sampleDt, referencePeriod: P,
  smallAt: main.smallAt, largeAt: main.largeAt, endTime, maxEnergyDrift: checked.maxEnergyDrift,
  refinement: { half: { smallAt: fine.smallAt, largeAt: fine.largeAt }, quarter: { smallAt: finest.smallAt, largeAt: finest.largeAt },
    maxRelativeThresholdError: Math.max(...["smallAt", "largeAt"].map(k => Math.abs(main[k] - finest[k]) / finest[k])) },
  checkpoints: checked.checkpoints.filter(x => x.steps * M.DT <= endTime),
  curve: checked.curve.filter(x => x[0] <= endTime),
  selection: { candidateSeeds: candidates.map(x => x.seed), rejectedForConvergence: rejected, pilotCount: probeN, pilotSpanRad: span,
    note: "Seed chosen for readable divergence. All displayed trajectories remain physical, uncorrected solutions." } };
fs.writeFileSync(path.join(__dirname, "seeds.json"), JSON.stringify(out, null, 2) + "\n");
fs.writeFileSync(path.join(__dirname, "seeds.js"), "// Generated by pick_seeds.js; do not edit.\nwindow.PENDULUM_RUN = " + JSON.stringify(out) + ";\n");
console.log("MEASURED", JSON.stringify({ seed, smallAt: out.smallAt, largeAt: out.largeAt, endTime,
  maxEnergyDrift: out.maxEnergyDrift, refinement: out.refinement }));
module.exports = { measure };
