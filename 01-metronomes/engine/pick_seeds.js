// Finds a starting state (seed) for each scene that fits the plan; writes seeds.json and seeds.js:  node pick_seeds.js
// The chosen starts are real simulations; they are only picked from those whose timing fits the scene.
// "Permanent sync" (stableFrom): measured at every step; from this moment to the end of the scene everyone stays within 5° of the shared rhythm.
const M = require("./sim.js"), fs = require("fs");
const gapDeg = (a, b) => Math.abs(((a - b) * 180 / Math.PI + 540) % 360 - 180);
const startGap = (s) => gapDeg(s.phases0[0], s.phases0[1]);

// stableFrom: the last moment in [0, end] when anyone strays more than 5° (every step). Closer than 20 s to the end counts as not permanent (null).
function stableFrom(opts, end) {
  const s = M.makeSim(opts); let lastBad = 0;
  while (s.t < end) { s.step(); s.order(); if (s.share < 1) lastBad = s.t; }
  return lastBad > end - 20 ? null : +(lastBad + 0.01).toFixed(2);
}
// fixed board: smallest phase difference between the two metronomes over [0, end] (every step)
function minGapFixed(opts, end) {
  const s = M.makeSim({ ...opts, fixed: true }); let mn = 999;
  while (s.t < end) { s.step(); s.order(); mn = Math.min(mn, gapDeg(s.ph[0], s.ph[1])); }
  return mn;
}
function pick(label, base, maxSeed, ok) {
  for (let seed = 1; seed <= maxSeed; seed++) { const r = ok({ ...base, seed }); if (r) { console.log(`${label}: seed ${seed} · ${r.note}`); return { ...base, seed, ...r.data }; } }
  throw new Error(label + ": no suitable seed");
}
const out = {};
// 1) two metronomes, free board, ±0.1% (the difference in Pantaleone's experiment was ~0.1%), at least 120° apart at the start (so the double click is heard);
//    permanent sync at 50-65 s
out.two = pick("Scene 1 (2 metronomes)", { n: 2, spread: 0.1 }, 400, (o) => {
  if (startGap(M.makeSim(o)) < 120) return null;
  const st = stableFrom(o, 100); if (st === null || st < 50 || st > 65) return null;
  return { note: `starting difference ${startGap(M.makeSim(o)).toFixed(0)}°, permanent sync at ${st} s`, data: { stableFrom: st } };
});
// 2) split screen: the same start on both sides (±0.1%, ≥120°). With ±0.3% the fixed pair drifts a full cycle in ~97 s, so
//    in a 70 s scene they would line up for a moment. Free side: permanent sync at 50-65 s;
//    fixed side: phase difference never below 30° for the whole scene (permanent sync + 12 s), so no one mistakes it for sync
out.split = pick("Scene 2 (split screen)", { n: 2, spread: 0.1 }, 400, (o) => {
  if (o.seed === out.two.seed || startGap(M.makeSim(o)) < 120) return null;   // must not repeat scene 1
  const st = stableFrom(o, 100); if (st === null || st < 50 || st > 65) return null;
  const mg = minGapFixed(o, st + 12); if (mg < 30) return null;
  return { note: `free side: permanent sync at ${st} s; fixed side: smallest phase difference ${mg.toFixed(0)}°`, data: { stableFrom: st, fixedMinGap: +mg.toFixed(1) } };
});
// 3) ten metronomes, ±0.3%, permanent sync at 55-70 s (shown at 2× speed)
out.ten = pick("Scene 3 (10 metronomes)", { n: 10, spread: 0.3 }, 60, (o) => {
  const st = stableFrom(o, 100); if (st === null || st < 55 || st > 70) return null;
  return { note: `permanent sync at ${st} s`, data: { stableFrom: st } };
});
// 4) one hundred metronomes, ±0.3%, permanent sync at 85-100 s; checked 60 s past that because the closing scene continues this simulation
out.hundred = pick("Scene 4 (100 metronomes)", { n: 100, spread: 0.3 }, 20, (o) => {
  const s = M.makeSim(o); while (s.t < 110 && s.lockedAt < 0) s.advance(1); if (s.lockedAt < 80 || s.lockedAt > 100) return null;
  const st = stableFrom(o, s.lockedAt + 60); if (st === null || st > 100) return null;
  return { note: `permanent sync at ${st} s (every step checked up to ${(s.lockedAt + 60).toFixed(0)} s)`, data: { stableFrom: st } };
});
// 0) opening: the first 15 s of 100 metronomes must be full chaos (under 20% in the shared rhythm)
{ const s = M.makeSim({ n: 100, spread: 0.3, seed: 1000 }); let mx = 0; for (let i = 0; i < 30; i++) { s.advance(0.5); s.order(); mx = Math.max(mx, s.share); }
  if (mx >= 0.2) throw new Error("opening is not chaotic"); out.opening = { n: 100, spread: 0.3, seed: 1000, maxShare15s: +mx.toFixed(2) };
  console.log(`Scene 0 (opening): seed 1000 · at most ${Math.round(mx * 100)}% in the shared rhythm during the first 15 s`); }
fs.writeFileSync(__dirname + "/seeds.json", JSON.stringify(out, null, 2));
fs.writeFileSync(__dirname + "/seeds.js", "// generated by pick_seeds.js; do not edit by hand\nwindow.SEEDS = " + JSON.stringify(out, null, 2) + ";\n");
console.log("seeds.json and seeds.js written");
